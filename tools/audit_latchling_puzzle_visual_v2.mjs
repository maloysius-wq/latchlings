import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'no-preference'});
const page=await ctx.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:8157/',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>typeof screen==='function'&&typeof startLevel==='function'&&window.LatchlingsStoryTheme);
await page.evaluate(()=>{screen('game');startLevel(400)});
await page.waitForSelector('#game.active .latchling');
await page.waitForTimeout(420);
await page.evaluate(()=>LatchlingsStoryTheme.close(false));
await page.waitForTimeout(120);
if(await page.locator('#storyCardOverlay.show').count())throw new Error('Story Card still open over puzzle');
await page.screenshot({path:'clean-puzzle-latchling-render-v2/puzzle-level-400-clean.png',fullPage:true});
if(errors.length)throw new Error(errors.join(' | '));
console.log('CLEAN_PUZZLE_LATCHLING_RENDER_V2_OK');
await browser.close();
