geometryAssert.equal(searchGeometry('corners',1001),'corners');
geometryAssert.throws(()=>searchGeometry('unknown',1),/geometry/);
geometryAssert.throws(()=>searchGeometry('corners',0),/attempt/);
const assert=require('node:assert/strict'),path=require('node:path');
const {loadCampaign}=require('../tools/campaign/runtime.cjs');
const {candidate,cooperation,fitsCooperation,cooperationFailures}=require('../tools/campaign/candidates.cjs');
const {levels,simulateState}=loadCampaign(path.resolve(__dirname,'..'));
const a=candidate({size:5,pieces:2,rocks:5,geometry:'lanes'},1234,51),b=candidate({size:5,pieces:2,rocks:5,geometry:'lanes'},1234,51);
assert.deepEqual(a,b,'offline candidate construction must be deterministic');
const occupied=[...a.pieces.map(p=>p.pos),...a.nests,...a.rocks].map(v=>v.join(','));assert.equal(new Set(occupied).size,occupied.length);
assert(a.pieces.every(p=>p.pos.every(v=>v>=0&&v<5)));assert(a.nests.every(p=>p.every(v=>v>=0&&v<5)));
const deps=cooperation(levels[50],simulateState);assert(deps.stops.length>0);assert(deps.stops.every(s=>s.helper!==s.traveler));
assert.equal(typeof deps.motif,'string','missing identity-independent dependency motif');
const renamed=JSON.parse(JSON.stringify(levels[50]));renamed.pieces.reverse();renamed.nests.reverse();renamed.solution=renamed.solution.map(([pi,dir])=>[1-pi,dir]);
assert.equal(cooperation(renamed,simulateState).motif,deps.motif,'renaming piece indices must not hide the same dependency pattern');
assert.equal(typeof fitsCooperation,'function','missing cooperation selection gate');
assert(fitsCooperation(deps,{minStops:1,minTravelers:1,minRelocations:0,minBeforeCapture:0}));
assert(!fitsCooperation(deps,{minStops:99,minTravelers:1,minRelocations:0,minBeforeCapture:0}));
assert(!fitsCooperation(deps,{minStops:1,minTravelers:99,minRelocations:0,minBeforeCapture:0}));
for(const stop of deps.stops){assert.deepEqual(stop.state.positions[stop.helper],stop.helperPosition);assert.equal(stop.result.reason,'piece');}
assert.equal(typeof cooperationFailures,'function','missing fresh Lanternwood curriculum verification');
const falseCapstone={...levels[50],id:96};
assert(cooperationFailures(falseCapstone,simulateState).some(error=>error.includes('capstone')),'elementary helper use cannot certify a capstone');
const repeatedMotif=new Set([cooperation(falseCapstone,simulateState).motif]);
assert(cooperationFailures(falseCapstone,simulateState,repeatedMotif).some(error=>error.includes('Repeated')),'capstones must have distinct dependency motifs');
const reminderOnly={...levels[50],id:52};
assert(cooperationFailures(reminderOnly,simulateState).some(error=>error.includes('intro')),'after the reminder, introduction must teach relocated helpers rather than repeat initial-wall errands');
const bent={size:5,pieces:[{color:'blue',suit:'spade',pos:[2,0]},{color:'coral',suit:'heart',pos:[4,2]}],nests:[[3,4],[4,4]],rocks:[],anchors:[],suitGates:[],colorGates:[],rails:[],turners:[[2,2,'CW']],switches:[],doors:[],solution:[[0,'R'],[0,'R'],[1,'R']]};
const bentDeps=cooperation(bent,simulateState);
assert(bentDeps.solved,'bent helper fixture must actually clear');
assert.equal(bentDeps.stops.length,1,'helper reached after a turn must not disappear from dependencies');
assert.equal(bentDeps.stops[0].helper,1);
assert.deepEqual(bentDeps.stops[0].helperPosition,[4,2]);
assert.equal(bentDeps.stops[0].finalDirection,'D');
const atTurn={...bent,pieces:[bent.pieces[0],{...bent.pieces[1],pos:[3,2]}],nests:[[2,4],[3,4]],solution:[[0,'R'],[0,'R'],[1,'R']]};
assert.equal(cooperation(atTurn,simulateState).stops[0]?.finalDirection,'D','a turn on the last traversed tile rotates before the helper blocks the next step');
const routed=candidate({size:7,pieces:3,rocks:6,anchors:2,suitGates:2,colorGates:2,rails:2,turners:2,links:2,geometry:'crossing'},729161,326);
assert.equal(routed.rails.length,2,'offline construction must honor the requested rail count');
assert.equal(routed.turners.length,2);
assert.equal(routed.switches.length,2);
assert.equal(routed.doors.length,2);
assert.deepEqual(routed.switches.map(v=>v[2]),[0,1]);
assert.deepEqual(routed.doors.map(v=>v[2]),[0,1],'every authored link suggestion has both a switch and door');
assert(routed.rails.every(v=>['U','D','L','R'].includes(v[2])));
assert(routed.turners.every(v=>['CW','CCW'].includes(v[2])));
const allPositions=[...routed.pieces.map(p=>p.pos),...routed.nests,...['rocks','anchors','suitGates','colorGates','rails','turners','switches','doors'].flatMap(field=>routed[field])].map(p=>p.slice(0,2).join(','));
assert.equal(new Set(allPositions).size,allPositions.length,'suggested route/state tiles cannot cover another tile, resident or nest');
assert.deepEqual(routed,candidate({size:7,pieces:3,rocks:6,anchors:2,suitGates:2,colorGates:2,rails:2,turners:2,links:2,geometry:'crossing'},729161,326));
console.log('PASS deterministic candidates, exclusive geometry and replayable cooperation dependencies, including bent helper arrivals');
